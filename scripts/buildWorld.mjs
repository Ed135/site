// Usage: node scripts/buildWorld.mjs
// Writes src/photos/world.ts: one simplified SVG path per country (Mercator, viewBox 0 0 360 220)
// from Natural Earth 50m (world-atlas). Re-run only if you want to change the simplification.
import fs from 'node:fs'
import path from 'node:path'
import { feature } from 'topojson-client'
import { iso1A2Code } from '@rapideditor/country-coder'

const X = (lon) => (lon + 180).toFixed(1)
const merc = (lat) => (180 / Math.PI) * Math.log(Math.tan(Math.PI / 4 + (Math.max(-85, Math.min(85, lat)) * Math.PI) / 360))
const Y = (lat) => (merc(75) - merc(lat)).toFixed(1) // Mercator, 75N at the top: equirectangular looks stretched sideways
const MIN_STEP = 0.25 // drop vertices closer than this (map units)
const MIN_AREA = 0.3 // drop islets below this bbox area

function ring(r) {
  const out = []
  let last
  for (const [lon, lat] of r) {
    if (last && Math.hypot(lon - last[0], lat - last[1]) < MIN_STEP) continue
    out.push([lon, lat])
    last = [lon, lat]
  }
  return out.length >= 3 ? 'M' + out.map(([lo, la]) => `${X(lo)} ${Y(la)}`).join('L') + 'Z' : ''
}

const topo = JSON.parse(fs.readFileSync(path.resolve(import.meta.dirname, '../node_modules/world-atlas/countries-50m.json'), 'utf8'))
const paths = {}
for (const f of feature(topo, topo.objects.countries).features) {
  const code = f.id ? iso1A2Code(String(f.id).padStart(3, '0')) : { Kosovo: 'XK' }[f.properties.name]
  if (!code || code === 'AQ') continue
  const polys = (f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates).map((p) => {
    // unwrap longitudes across the antimeridian so Russia/Fiji stay in one piece (the overflow is clipped by the viewBox)
    let off = 0
    return p[0].map((c, i) => {
      if (i) { const d = c[0] - p[0][i - 1][0]; if (d < -180) off += 360; else if (d > 180) off -= 360 }
      return [c[0] + off, c[1]]
    })
  })
  const box = (r) => { const xs = r.map((c) => c[0]), ys = r.map((c) => c[1]); return { x0: Math.min(...xs), x1: Math.max(...xs), y0: Math.min(...ys), y1: Math.max(...ys) } }
  const boxes = polys.map(box)
  const area = (b) => (b.x1 - b.x0) * (b.y1 - b.y0)
  const main = boxes.reduce((a, b) => (area(b) > area(a) ? b : a))
  const mx = (main.x0 + main.x1) / 2, my = (main.y0 + main.y1) / 2
  // keep the mainland and near neighbours; far overseas territories (French Guiana, Hawaii) would blow up the zoom
  const d = polys
    .filter((_, k) => area(boxes[k]) >= MIN_AREA && Math.hypot((boxes[k].x0 + boxes[k].x1) / 2 - mx, (boxes[k].y0 + boxes[k].y1) / 2 - my) < 62)
    .map((r) => ring(r))
    .join('')
  if (d) paths[code] = (paths[code] ?? '') + d
}

const file = path.resolve(import.meta.dirname, '../src/photos/world.ts')
fs.writeFileSync(file, `// Generated by scripts/buildWorld.mjs - do not edit. Country code -> SVG path, viewBox 0 0 360 220.\nexport const world: Record<string, string> = ${JSON.stringify(paths)}\n`)
console.log(Object.keys(paths).length, 'countries,', (fs.statSync(file).size / 1024).toFixed(0), 'KB')
